/** Shared deterministic renderers for the site CLIs and the server-only draft compiler. */
import { FEATURED_IMAGE_KEYS } from './featured-image.mjs';

function tsStringArray(values) {
	return `[${values.map((value) => JSON.stringify(value)).join(', ')}]`;
}

function renderMetadata(metadata) {
	const lines = [
		`\t\t\tdate: ${JSON.stringify(metadata.date)},`,
		`\t\t\ttitle: ${JSON.stringify(metadata.title)},`,
		`\t\t\tsummary: ${JSON.stringify(metadata.summary)},`,
		`\t\t\ttags: ${tsStringArray(metadata.tags)},`,
		'\t\t\tpublished: true,',
	];
	if (typeof metadata.updated === 'string') lines.push(`\t\t\tupdated: ${JSON.stringify(metadata.updated)},`);
	for (const key of FEATURED_IMAGE_KEYS) {
		if (typeof metadata[key] === 'string') lines.push(`\t\t\t${key}: ${JSON.stringify(metadata[key])},`);
	}
	return lines.join('\n');
}

function renderEntry(entry) {
	return [
		'\t{',
		`\t\tslug: ${JSON.stringify(entry.slug)},`,
		'\t\tmetadata: {',
		renderMetadata(entry.metadata),
		'\t\t},',
		`\t\tsourcePath: ${JSON.stringify(entry.sourcePath)},`,
		`\t\tloadComponent: () => import(${JSON.stringify(`../../content/log/${entry.file}`)}),`,
		'\t},',
	].join('\n');
}

/**
 * @param {import('./log-content.mjs').LogEntry[]} entries
 * @param {import('prettier').Options} options
 * @param {string} [filepath]
 */
export async function renderLogManifest(entries, options, filepath = 'src/lib/generated/log-manifest.ts') {
	const { format } = await import('prettier');
	const published = entries.filter((entry) => entry.metadata.published === true);
	const body =
		published.length > 0 ? `${published.map(renderEntry).join('\n')}\n` : '\t// No entries are published yet.\n';
	const content = `// GENERATED by scripts/build-log-manifest.mjs — do not edit by hand.
// \`just log-manifest-check\` (wired into \`just check\`) fails on drift.
//
// PUBLISHED entries ONLY (B1 fix, PR #33 review comment
// https://github.com/Great-Falls-Tool-Bus/gftb-site/pull/33#issuecomment-5364998251):
// unpublished drafts are excluded HERE, at generation time, so neither their
// metadata nor their component ever becomes an import reachable from the
// client bundle. See docs/content-train.md and src/lib/public-logs.ts.
import type { Component } from 'svelte';

import type { PublicLogMetadata } from '../public-log-schema';

export interface GeneratedLogEntry {
	slug: string;
	metadata: PublicLogMetadata;
	sourcePath: string;
	loadComponent: () => Promise<{ default: Component }>;
}

export const publishedLogEntries: GeneratedLogEntry[] = [
${body}];
`;
	return format(content, { ...options, filepath });
}

/** Resolve the existing repository metadata fallback without reading ambient files. */
export function resolveSourceRepository(manifest, pkg) {
	let repoUrl = '';
	const github = manifest?.repo?.github;
	if (typeof github === 'string' && github.includes('/')) {
		repoUrl = `https://github.com/${github}`;
	} else {
		const url = typeof pkg?.repository === 'string' ? pkg.repository : pkg?.repository?.url;
		if (typeof url === 'string' && url) {
			repoUrl = url
				.replace(/^git\+/, '')
				.replace(/\.git$/, '')
				.replace(/^git@github\.com:/, 'https://github.com/');
		}
	}
	if (!repoUrl) throw new Error('source-map-build: could not resolve repo URL from tinyland.repo.json or package.json');
	const branch = (typeof manifest?.repo?.defaultBranch === 'string' && manifest.repo.defaultBranch) || 'main';
	return { repoUrl, branch };
}

/**
 * @param {{ repoUrl: string; branch: string }} repository
 * @param {string[]} pageFiles Repository-relative POSIX paths, as supplied by the existing walker.
 * @param {import('./log-content.mjs').LogEntry[]} entries
 */
export function renderSourceMap(repository, pageFiles, entries) {
	const routes = {};
	for (const file of pageFiles) {
		const directory = file.slice('src/routes'.length, -'/+page.svelte'.length);
		const segments = directory
			.split('/')
			.filter((segment) => segment && !(segment.startsWith('(') && segment.endsWith(')')));
		const route = segments.length ? `/${segments.join('/')}` : '/';
		if (!route.includes('[')) routes[route] = file;
	}
	for (const entry of entries) {
		if (entry.metadata.published === true) routes[`/log/${entry.slug}`] = entry.sourcePath;
	}
	const sortedRoutes = {};
	for (const key of Object.keys(routes).sort()) sortedRoutes[key] = routes[key];
	return `${JSON.stringify(
		{
			$generated: 'generated by just source-map-build; do not edit by hand',
			repoUrl: repository.repoUrl,
			branch: repository.branch,
			routes: sortedRoutes,
		},
		null,
		'\t',
	)}\n`;
}
