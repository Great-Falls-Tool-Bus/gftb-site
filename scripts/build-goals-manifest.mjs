// `just goals-manifest-build`: derive src/lib/generated/goals-manifest.ts
// from src/content/goals/*.md, PUBLISHED entries only, the log-manifest
// pattern (scripts/build-log-manifest.mjs) applied to the home page's
// near-term goals, help asks, and member benefits. The internal `source`
// provenance key is dropped here so it never reaches the bundle.
// `just goals-manifest-check` runs this then `git diff --exit-code`.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { format, resolveConfig } from 'prettier';

import {
	FEATURED_IMAGE_KEYS,
	assertFeaturedImageFrontmatter,
	assertPublishedImageAsset,
} from './lib/featured-image.mjs';
import { readGoalEntries } from './lib/goals-content.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const GOALS_DIR = path.join(ROOT, 'src', 'content', 'goals');
const OUT_FILE = path.join(ROOT, 'src', 'lib', 'generated', 'goals-manifest.ts');

const KINDS = new Set(['goal', 'help', 'benefit']);
// Mirrors src/lib/public-goal-schema.ts (the binding contract, exercised by
// src/lib/public-goal-schema.test.ts over every content file); the generator
// refuses the same shapes so an invalid file never reaches the manifest.
const ALLOWED_KEYS = new Set([
	'kind',
	'order',
	'title',
	'published',
	'window',
	'cta_label',
	'cta_href',
	'source',
	...FEATURED_IMAGE_KEYS,
]);

function renderEntry(entry) {
	const m = entry.metadata;
	const unknown = Object.keys(m).filter((key) => !ALLOWED_KEYS.has(key));
	if (unknown.length > 0) throw new Error(`${entry.file}: unsupported frontmatter keys: ${unknown.join(', ')}`);
	if (typeof m.published !== 'boolean') throw new Error(`${entry.file}: published must be a boolean`);
	if (!KINDS.has(m.kind)) throw new Error(`${entry.file}: kind must be goal, help, or benefit`);
	if (/—/u.test(`${m.title} ${m.window ?? ''} ${m.cta_label ?? ''} ${entry.text}`)) {
		throw new Error(`${entry.file}: no em dashes in public copy`);
	}
	if (m.cta_href !== undefined && !/^(\/|https:\/\/)/u.test(String(m.cta_href))) {
		throw new Error(`${entry.file}: cta_href must be a site-relative path or an https URL`);
	}
	const order = Number.parseInt(String(m.order), 10);
	if (!Number.isInteger(order) || order < 0) throw new Error(`${entry.file}: order must be a non-negative integer`);
	if (typeof m.title !== 'string' || m.title.trim().length < 3) throw new Error(`${entry.file}: title required`);
	if ((m.cta_label === undefined) !== (m.cta_href === undefined)) {
		throw new Error(`${entry.file}: cta_label and cta_href travel together`);
	}
	// Featured-image group: same fail-closed checks as the schema, plus the
	// committed-asset check (renderEntry only ever sees published entries).
	assertFeaturedImageFrontmatter(m, entry.file);
	assertPublishedImageAsset(m, entry.file, ROOT);
	const lines = [
		'\t{',
		`\t\tslug: ${JSON.stringify(entry.slug)},`,
		'\t\tmetadata: {',
		`\t\t\tkind: ${JSON.stringify(m.kind)},`,
		`\t\t\torder: ${order},`,
		`\t\t\ttitle: ${JSON.stringify(m.title)},`,
	];
	if (typeof m.window === 'string' && m.window.length > 0) lines.push(`\t\t\twindow: ${JSON.stringify(m.window)},`);
	if (typeof m.cta_label === 'string') {
		lines.push(`\t\t\tcta_label: ${JSON.stringify(m.cta_label)},`);
		lines.push(`\t\t\tcta_href: ${JSON.stringify(m.cta_href)},`);
	}
	for (const key of FEATURED_IMAGE_KEYS) {
		if (typeof m[key] === 'string') lines.push(`\t\t\t${key}: ${JSON.stringify(m[key])},`);
	}
	lines.push(
		'\t\t\tpublished: true,',
		'\t\t},',
		`\t\ttext: ${JSON.stringify(entry.text)},`,
		`\t\tsourcePath: ${JSON.stringify(entry.sourcePath)},`,
		'\t},',
	);
	return lines.join('\n');
}

async function main() {
	const entries = readGoalEntries(GOALS_DIR);
	const published = entries.filter((entry) => entry.metadata.published === true);
	const body =
		published.length > 0 ? `${published.map(renderEntry).join('\n')}\n` : '\t// No entries are published yet.\n';
	const content = `// GENERATED by scripts/build-goals-manifest.mjs. Do not edit by hand.
// \`just goals-manifest-check\` (wired into \`just check\`) fails on drift.
//
// PUBLISHED entries ONLY: unpublished drafts are excluded at generation time,
// so their text is never an import reachable from the client bundle. The
// internal \`source\` provenance key is never emitted. See docs/content-train.md
// and src/lib/public-goals.ts.
import type { PublicGoalMetadata } from '../public-goal-schema';

export interface GeneratedGoalEntry {
	slug: string;
	metadata: PublicGoalMetadata;
	text: string;
	sourcePath: string;
}

export const publishedGoalEntries: GeneratedGoalEntry[] = [
${body}];
`;
	const prettierOptions = (await resolveConfig(OUT_FILE)) ?? {};
	const formatted = await format(content, { ...prettierOptions, filepath: OUT_FILE });
	await fs.mkdir(path.dirname(OUT_FILE), { recursive: true });
	await fs.writeFile(OUT_FILE, formatted);
	console.log(
		`goals-manifest-build: ${published.length} published of ${entries.length} goal entr${entries.length === 1 ? 'y' : 'ies'} -> src/lib/generated/goals-manifest.ts`,
	);
}

main().catch((err) => {
	console.error(err);
	process.exit(1);
});
