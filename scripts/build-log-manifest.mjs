// `just log-manifest-build` — derive src/lib/generated/log-manifest.ts from
// src/content/log/*.svx.
//
// B1 fix (PR #33 review comment
// https://github.com/Great-Falls-Tool-Bus/gftb-site/pull/33#issuecomment-5364998251):
// the previous loader (src/lib/public-logs.ts) built its published/draft
// split at RUNTIME from an eager `import.meta.glob` over every entry, so
// every draft's full prose and metadata were static imports in the module
// graph and shipped to every visitor in build/_app/immutable/chunks/*
// regardless of the `published` filter, which only ran after the bytes were
// already bundled.
//
// This script moves the split to BUILD time and OUTSIDE Vite's module
// graph entirely (plain node:fs via scripts/lib/log-content.mjs, never
// import.meta.glob): it writes only entries with `published: true`, each as
// a literal `import('../../content/log/<slug>.svx')` call. An unpublished
// slug therefore never appears as an import specifier anywhere reachable
// from src/lib/public-logs.ts, so Vite/Rollup has no path by which it could
// bundle one — this is stronger than relying on tree-shaking an eager glob,
// which is what the review asked for when it said "gate at the glob pattern
// level instead, e.g. a generated include list".
//
// Output is deterministic (file order, tab-indented, trailing newline).
// `just log-manifest-check` runs this then `git diff --exit-code`, mirroring
// scripts/build-source-map.mjs, so drift fails CI the same way.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { format, resolveConfig } from 'prettier';

import { readLogEntries } from './lib/log-content.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const LOG_DIR = path.join(ROOT, 'src', 'content', 'log');
const OUT_FILE = path.join(ROOT, 'src', 'lib', 'generated', 'log-manifest.ts');

function tsStringArray(values) {
	return `[${values.map((value) => JSON.stringify(value)).join(', ')}]`;
}

function renderMetadata(metadata) {
	const lines = [
		`\t\t\tdate: ${JSON.stringify(metadata.date)},`,
		`\t\t\ttitle: ${JSON.stringify(metadata.title)},`,
		`\t\t\tsummary: ${JSON.stringify(metadata.summary)},`,
		`\t\t\ttags: ${tsStringArray(metadata.tags)},`,
		`\t\t\tpublished: true,`,
	];
	if (typeof metadata.updated === 'string') {
		lines.push(`\t\t\tupdated: ${JSON.stringify(metadata.updated)},`);
	}
	return lines.join('\n');
}

function renderEntry(entry) {
	return [
		'\t{',
		`\t\tslug: ${JSON.stringify(entry.slug)},`,
		'\t\tmetadata: {',
		renderMetadata(entry.metadata),
		'\t\t},',
		`\t\tsourcePath: ${JSON.stringify(entry.sourcePath)},`,
		`\t\tloadComponent: () => import(${JSON.stringify(`../../content/log/${entry.file}`)}),`,
		'\t},',
	].join('\n');
}

async function main() {
	const entries = readLogEntries(LOG_DIR);
	const published = entries.filter((entry) => entry.metadata.published === true);

	const body =
		published.length > 0 ? `${published.map(renderEntry).join('\n')}\n` : '\t// No entries are published yet.\n';

	const content = `// GENERATED by scripts/build-log-manifest.mjs — do not edit by hand.
// \`just log-manifest-check\` (wired into \`just check\`) fails on drift.
//
// PUBLISHED entries ONLY (B1 fix, PR #33 review comment
// https://github.com/Great-Falls-Tool-Bus/gftb-site/pull/33#issuecomment-5364998251):
// unpublished drafts are excluded HERE, at generation time, so neither their
// metadata nor their component ever becomes an import reachable from the
// client bundle. See docs/content-train.md and src/lib/public-logs.ts.
import type { Component } from 'svelte';

import type { PublicLogMetadata } from '../public-log-schema';

export interface GeneratedLogEntry {
	slug: string;
	metadata: PublicLogMetadata;
	sourcePath: string;
	loadComponent: () => Promise<{ default: Component }>;
}

export const publishedLogEntries: GeneratedLogEntry[] = [
${body}];
`;

	const prettierOptions = (await resolveConfig(OUT_FILE)) ?? {};
	const formattedContent = await format(content, { ...prettierOptions, filepath: OUT_FILE });

	await fs.mkdir(path.dirname(OUT_FILE), { recursive: true });
	await fs.writeFile(OUT_FILE, formattedContent);

	console.log(
		`log-manifest-build: ${published.length} published of ${entries.length} log entr${entries.length === 1 ? 'y' : 'ies'} -> src/lib/generated/log-manifest.ts`,
	);
}

main().catch((err) => {
	console.error(err);
	process.exit(1);
});
