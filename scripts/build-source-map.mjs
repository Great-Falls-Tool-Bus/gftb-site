// `just source-map-build` — derive the page source map from the routes tree.
//
// Ported from the demo site (greatfallstoolbus.org@origin/main
// scripts/build-source-map.mjs, operator commit #94) and extended for the
// public log (B1.2): in addition to every src/routes/**/+page.svelte, each
// PUBLISHED src/content/log/*.svx post is mapped at its /log/<slug>
// permalink, so the "Edit this page" affordance is wired PER POST.
//
// Unpublished drafts are excluded (B1 fix, PR #33 review): the review found
// draft slugs shipping here too (source-map.json is a build output, walked
// by leak-scan, and read by src/lib/components/SourceLink.svelte), which
// would advertise a draft's existence — and, at the `/log/<slug>` permalink
// it names — even though the draft itself never prerenders.
//
// Why derived, not per-page hand-links: the map is generated from
// architectural zero so a new page or post cannot silently lack the
// affordance, and NO org/repo string is hardcoded in any component (it flows
// from tinyland.repo.json / package.json).
//
// Output is deterministic (sorted route keys, tab-indented, trailing newline).
// `//:source_map_drift_test` runs this generator read-only with `--check`.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { readLogEntries } from './lib/log-content.mjs';
import { generatedFileCheckMode, writeOrCheckGeneratedFile } from './lib/generated-file.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const ROUTES_DIR = path.join(ROOT, 'src', 'routes');
const LOG_DIR = path.join(ROOT, 'src', 'content', 'log');
const OUT_FILE = path.join(ROOT, 'src', 'lib', 'generated', 'source-map.json');

const DEFAULT_BRANCH = 'main';
const CHECK_ONLY = generatedFileCheckMode(process.argv.slice(2));

async function readJson(file) {
	try {
		return JSON.parse(await fs.readFile(file, 'utf8'));
	} catch {
		return null;
	}
}

async function resolveRepo() {
	const manifest = await readJson(path.join(ROOT, 'tinyland.repo.json'));
	const pkg = await readJson(path.join(ROOT, 'package.json'));

	let repoUrl = '';
	const github = manifest?.repo?.github;
	if (typeof github === 'string' && github.includes('/')) {
		repoUrl = `https://github.com/${github}`;
	} else {
		const url = typeof pkg?.repository === 'string' ? pkg.repository : pkg?.repository?.url;
		if (typeof url === 'string' && url) {
			repoUrl = url
				.replace(/^git\+/, '')
				.replace(/\.git$/, '')
				.replace(/^git@github\.com:/, 'https://github.com/');
		}
	}
	if (!repoUrl) {
		throw new Error('source-map-build: could not resolve repo URL from tinyland.repo.json or package.json');
	}

	const branch = (typeof manifest?.repo?.defaultBranch === 'string' && manifest.repo.defaultBranch) || DEFAULT_BRANCH;

	return { repoUrl, branch };
}

// SvelteKit route id from a +page.svelte path, base-stripped ("/" for root).
function routeIdFor(relPageFile) {
	const dir = path.dirname(relPageFile).slice('src/routes'.length);
	const segments = dir.split('/').filter((s) => s && !(s.startsWith('(') && s.endsWith(')')));
	return segments.length ? `/${segments.join('/')}` : '/';
}

async function walkPageFiles(dir) {
	const out = [];
	for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			out.push(...(await walkPageFiles(full)));
		} else if (entry.name === '+page.svelte') {
			out.push(full);
		}
	}
	return out;
}

async function main() {
	const { repoUrl, branch } = await resolveRepo();
	const pageFiles = await walkPageFiles(ROUTES_DIR);

	const routes = {};
	for (const full of pageFiles) {
		const rel = path.relative(ROOT, full).split(path.sep).join('/');
		const routeId = routeIdFor(rel);
		// Parameterised routes ([slug], [n]) have no single source page a
		// reader can usefully edit; posts are mapped per permalink below.
		if (routeId.includes('[')) continue;
		routes[routeId] = rel;
	}

	// Per-post permalinks: /log/<slug> -> the .svx source itself (B1.2).
	// Published entries only (B1 fix) — an unpublished draft has no
	// permalink to map and its slug must not appear in this build output.
	for (const entry of readLogEntries(LOG_DIR)) {
		if (entry.metadata.published !== true) continue;
		routes[`/log/${entry.slug}`] = entry.sourcePath;
	}

	const sortedRoutes = {};
	for (const key of Object.keys(routes).sort()) {
		sortedRoutes[key] = routes[key];
	}

	const doc = {
		$generated: 'generated by just source-map-build; do not edit by hand',
		repoUrl,
		branch,
		routes: sortedRoutes,
	};

	const content = `${JSON.stringify(doc, null, '\t')}\n`;
	await writeOrCheckGeneratedFile(OUT_FILE, content, {
		check: CHECK_ONLY,
		label: 'source-map-check',
	});

	console.log(
		`source-map-build: mapped ${Object.keys(sortedRoutes).length} route(s) -> src/lib/generated/source-map.json`,
	);
}

main().catch((err) => {
	console.error(err);
	process.exit(1);
});
